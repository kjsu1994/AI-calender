import { test, expect } from '@playwright/test'

test('time-based records are separate from schedules and support confirmed edit and deletion', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/'); await page.getByRole('button', { name: '샘플로 시작하기' }).click()
  await page.locator('.workspace-tabs').getByRole('button', { name: /시간별 기록/ }).click()
  await page.getByRole('button', { name: '기록 추가', exact: true }).click()
  await page.getByLabel('기록 제목', { exact: true }).fill('시간대 고객 미팅')
  await page.getByLabel('기록 내용', { exact: true }).fill('견적 수정 요청받음. 다음 주 수요일까지 회신하기.')
  await page.getByLabel('일정 연결 (선택)').selectOption({ label: '일정에 연결하지 않음' })
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  const card = page.locator('.record-card').filter({ hasText: '시간대 고객 미팅' })
  await expect(card).toContainText('12:00 – 13:00')
  await expect(card).toContainText('견적 수정 요청받음.')
  await page.locator('.workspace-tabs').getByRole('button', { name: '일정', exact: true }).click()
  await expect(page.locator('.event-row').filter({ hasText: '시간대 고객 미팅' })).toHaveCount(0)
  await page.locator('.workspace-tabs').getByRole('button', { name: /시간별 기록/ }).click()
  await page.getByRole('button', { name: '시간대 고객 미팅 기록 수정' }).click()
  await page.getByLabel('기록 내용', { exact: true }).fill('견적 검토 완료. 다음 주 계약 진행.')
  await page.getByRole('button', { name: '기록 변경 확인' }).click()
  await expect(card).toContainText('견적 수정 요청받음.')
  await page.getByRole('button', { name: '확인하고 실행' }).click()
  await expect(card).toContainText('견적 검토 완료.')
  await page.reload()
  await page.locator('.workspace-tabs').getByRole('button', { name: /시간별 기록/ }).click()
  await expect(card).toContainText('견적 검토 완료.')
  await page.getByRole('button', { name: '시간대 고객 미팅 기록 수정' }).click()
  await page.getByRole('button', { name: '기록 삭제', exact: true }).click()
  await page.getByRole('button', { name: '취소', exact: true }).click()
  await expect(card).toBeVisible()
  await page.getByRole('button', { name: '시간대 고객 미팅 기록 수정' }).click()
  await page.getByRole('button', { name: '기록 삭제', exact: true }).click()
  await page.getByRole('button', { name: '확인하고 실행' }).click()
  await expect(card).toHaveCount(0)
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
