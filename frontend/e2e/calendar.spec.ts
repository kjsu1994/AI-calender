import { test, expect } from '@playwright/test'

test('sample calendar supports create, confirmed edit, cancel delete, and confirmed delete', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button', { name: '샘플로 시작하기' }).click()
  await expect(page.getByRole('heading', { name: '프로젝트 아이디어 정리' })).toBeVisible()
  await page.getByRole('button', { name: '일정 추가', exact: true }).click()
  await page.getByLabel('일정 이름').fill('검증용 치과 예약')
  await page.getByRole('button', { name: '일정 저장', exact: true }).click()
  await expect(page.getByRole('heading', { name: '검증용 치과 예약', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '검증용 치과 예약 상세 보기' }).click()
  await page.getByLabel('일정 이름').fill('변경된 치과 예약')
  await page.getByRole('button', { name: '변경 내용 확인' }).click()
  await expect(page.getByRole('heading', { name: '검증용 치과 예약', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '확인하고 실행' }).click()
  await expect(page.getByRole('heading', { name: '변경된 치과 예약', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '변경된 치과 예약 상세 보기' }).click()
  await page.getByRole('button', { name: '삭제', exact: true }).click()
  await page.getByRole('button', { name: '취소', exact: true }).click()
  await expect(page.getByRole('heading', { name: '변경된 치과 예약', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '변경된 치과 예약 상세 보기' }).click()
  await page.getByRole('button', { name: '삭제', exact: true }).click()
  await page.getByRole('button', { name: '확인하고 실행' }).click()
  await expect(page.getByRole('heading', { name: '변경된 치과 예약', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: '프로젝트 아이디어 정리' })).toBeVisible()
  await page.getByRole('button', { name: '월간 보기', exact: true }).click()
  await expect(page.locator('.month-grid')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
  await page.screenshot({ path: `test-results/calendar-${test.info().project.name}.png`, fullPage: true })
})

test('sessions are isolated and writes require CSRF', async ({ browser, page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: '샘플로 시작하기' })).toBeVisible()
  const unauth = await page.request.get('/api/events?from=2026-09-01&to=2026-10-01')
  expect(unauth.status()).toBe(401)
  const csrf = await page.request.post('/api/auth/demo')
  expect(csrf.status()).toBe(403)
  await page.getByRole('button', { name: '샘플로 시작하기' }).click()
  await expect(page.getByRole('button', { name: '일정 추가', exact: true })).toBeEnabled()
  const another = await browser.newContext()
  const otherPage = await another.newPage(); await otherPage.goto('http://localhost:8085')
  await expect(otherPage.getByRole('button', { name: '샘플로 시작하기' })).toBeVisible()
  await another.close()
})

